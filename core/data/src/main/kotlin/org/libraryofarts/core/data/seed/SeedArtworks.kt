/**
 * A small, fully offline starter collection. Every work is public domain; the
 * image files are public-domain reproductions hosted by Wikimedia Commons.
 * Metadata is checked against the holding museum's published record.
 *
 * We ship this so a fresh install has a beautiful, useful library even with no
 * network and no API keys. Museum APIs enrich it when available.
 */
object SeedArtworks {
    private fun commons(file: String, width: Int = 1600): String {
        val encoded = URLEncoder.encode(file, "UTF-8").replace("+", "%20")
        return "https://commons.wikimedia.org/wiki/Special:FilePath/$encoded?width=$width"
    }

    private fun palette(vararg values: Long): List<PaletteColor> = values.mapIndexed { index, value ->
        PaletteColor(
            argb = value,
            hex = "#%06X".format(value and 0xFFFFFF),
            population = (1f - index * 0.14f).coerceAtLeast(0.1f),
            name = when {
                index == 0 -> "Dominant"
                else -> "Accent ${index + 1}"
            },
        )
    }

    private fun art(
        id: String,
        title: String,
        artist: Artist?,
        year: String,
        yearStart: Int?,
        yearEnd: Int?,
        genre: String,
        period: String,
        movement: String?,
        medium: String,
        dimensions: String,
        museum: org.libraryofarts.core.model.Museum,
        location: String?,
        file: String,
        width: Int,
        height: Int,
        description: String,
        credit: String,
        tags: List<String>,
        moods: List<String>,
        subjects: List<String>,
        colors: List<PaletteColor>,
        annotations: List<ArtworkAnnotation> = emptyList(),
        related: List<String> = emptyList(),
        highlight: Boolean = false,
    ): Artwork = Artwork(
        id = "seed:$id",
        source = ArtSource.OFFLINE_PACK,
        sourceId = id,
        title = title,
        artist = artist,
        year = year,
        yearStart = yearStart,
        yearEnd = yearEnd,
        genre = genre,
        period = period,
        movement = movement,
        medium = medium,
        dimensions = dimensions,
        museum = museum,
        location = location,
        palette = colors,
        image = ArtworkImage(
            thumbnailUrl = commons(file, 800),
            fullUrl = commons(file, 2400),
            width = width,
            height = height,
            creditLine = credit,
            altText = "$title by ${artist?.name ?: "an unknown artist"}, $year. $description",
        ),
        description = description,
        license = License.CC0.copy(creditLine = credit),
        provenance = listOf(ProvenanceEntry(description = credit)),
        tags = tags,
        moods = moods,
        subjects = subjects,
        annotations = annotations,
        isHighlight = highlight,
        isRarelyViewed = tags.contains("hidden gem"),
        creditLine = credit,
        packId = "starter",
    )

